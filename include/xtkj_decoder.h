#ifndef XTKJ_DECODER_H
#define XTKJ_DECODER_H
#include <future>
#include <string>
#include <vector>
using namespace std;
namespace xtkj {

/**
 * @description: 解码器状态枚举
 */
enum DecoderStatus {
    DECODER_STATUS_IDLE    = 0,  // 未打开/空闲状态
    DECODER_STATUS_OPENING = 1,  // 正在打开中
    DECODER_STATUS_OPENED  = 2,  // 正常打开/运行中
    DECODER_STATUS_FAILED  = 3   // 打开失败
};

class IDecoder {
  public:
    /**
     * @description: 初始化解码器
     * @param {int} decode_thread_num 解码线程索引/实例编号
     * @param {int} frame_interval 帧间隔，1表示每帧都处理，2表示隔一帧处理
     * @return 0成功，其他失败
     */
    virtual int init(int timeout_open_ms = 10000) = 0;
    /**
     * @description: 获取解码的帧数据（BGR格式）及视频信息
     * @return long数组，分别为 [mat数据地址, 宽度, 高度, 时间戳(毫秒), 帧率,
     * 码率, 总帧数]
     *         - [0] BGR数据地址：需要调用free()释放
     *         - [1] 宽度：图像宽度（像素）
     *         - [2] 高度：图像高度（像素）
     *         返回空数组表示超时或错误
     */
    virtual vector<long long> get_frame() = 0;
    /**
     * @description: 开始拉取视频流或打开本地视频文件
     * @param {string} video_path RTSP流地址(rtsp://)或本地视频文件路径
     * @param {int} is_mpp 是否使用MPP硬件解码（仅RTSP流，0=软解，1=硬解）
     * @param {int} interval 帧间隔（0=全部帧，1=跳帧）
     * @param {int} timeout_frame 获取帧超时时间（毫秒）
     * @return 0成功，非0失败
     * @note 自动识别RTSP流和本地文件路径
     */
    virtual int start_pull(string video_path,
                           int    is_mpp           = 0,
                           int    interval         = 1,
                           int    timeout_frame_ms = 200,
                           bool   auto_reopen      = true) = 0;
    /**
     * @description: 停止视频拉取/读取
     * @return 0成功
     */
    virtual int stop() = 0;
    /**
     * @description: 获取空帧次数（用于监控连接状态）
     * @return 空帧累计次数
     */
    virtual int get_null_times() = 0;
    /**
     * @description: 获取当前视频源路径
     * @return RTSP地址或本地文件路径
     */
    virtual string get_rtsp() = 0;
    /**
     * @description: 获取视频帧率（FPS）
     * @return 帧率，RTSP流和本地文件均支持，失败返回0
     */
    virtual double get_fps() = 0;
    /**
     * @description: 获取视频码率（bps）
     * @return 码率（比特率/秒），RTSP流和本地文件均支持，失败返回0
     */
    virtual int64_t get_bitrate() = 0;
    /**
     * @description: 获取视频总帧数
     * @return 总帧数，仅本地文件支持，RTSP流返回-1
     */
    virtual int64_t get_total_frames() = 0;
    virtual int     get_frame_height() = 0;
    virtual int     get_frame_width()  = 0;
    /**
     * @description: 获取解码器打开状态
     * @return DecoderStatus枚举值：
     *         DECODER_STATUS_IDLE (0) - 未打开/空闲状态
     *         DECODER_STATUS_OPENING (1) - 正在打开中
     *         DECODER_STATUS_OPENED (2) - 正常打开/运行中
     *         DECODER_STATUS_FAILED (3) - 打开失败
     */
    virtual int get_status() = 0;
    /**
     * @description: 设置本地视频文件循环播放模式（仅对本地文件有效）
     * @param {bool} loop true=循环播放（默认），false=播放一次后自动停止
     * @note 必须在start_pull()之前调用才能生效
     *       对RTSP流无效
     */
    virtual void set_loop_playback(bool loop) = 0;
    /**
     * @description: 设置RTSP流中断后是否自动重连
     * @param {bool} auto_reopen true=自动重连（默认），false=不自动重连
     * @note 仅对RTSP流有效，对本地文件无效
     *       可以在start_pull()之前或者运行时调用
     */
    virtual void set_auto_reopen(bool auto_reopen) = 0;
    /**
     * @description: 获取RTSP流中断后是否自动重连的设置
     * @return true=自动重连，false=不自动重连
     */
    virtual bool get_auto_reopen() = 0;
    /**
     * @description: 获取是否保持重连状态
     * @return true=保持重连，false=不保持重连
     */
    virtual bool get_keep_reopen() = 0;
    /**
     * @description: 设置是否保持重连状态
     * @param {bool} keep_reopen true=保持重连，false=不保持重连
     */
    virtual void set_keep_reopen(bool keep_reopen) = 0;

    virtual ~IDecoder() noexcept = default;
};
extern "C" IDecoder* createDecoder();
extern "C" void      releaseDecoder(IDecoder* pDecoder);
}  // namespace xtkj

#endif
